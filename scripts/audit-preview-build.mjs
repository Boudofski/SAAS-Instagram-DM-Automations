import { spawnSync } from "node:child_process";
import { PrismaClient } from "@prisma/client";
import { migrationUrl } from "./migration-url.mjs";
if (process.env.VERCEL_ENV !== "preview") throw new Error("Isolated preview only");
const db = new PrismaClient();
const snapshot = async () => ({ automations:await db.automation.count(), links:await db.automationTrackedLink.count(), totals:await db.listener.aggregate({_sum:{dmCount:true,commentCount:true}}) });
const before = await snapshot();
const migration=spawnSync("npx",["prisma","migrate","deploy"],{env:{...process.env,DATABASE_URL:migrationUrl(process.env)},stdio:"inherit"});
if(migration.status) process.exit(migration.status);
const after=await snapshot();
await db.$disconnect();
if(JSON.stringify(before)!==JSON.stringify(after))throw new Error("Migration changed existing record counts or reply totals");
console.log("Audit migration verified: existing rows and reply totals preserved.");
const build=spawnSync("npm",["run","vercel-build"],{stdio:"inherit"});process.exit(build.status||0);
